#!/usr/bin/env python3
"""Generate the MaTouch-only 64/80 px Montserrat fonts.

On BOARD_MATOUCH21, UIScale.h maps UI_FONT_32 -> 64 px and UI_FONT_40 -> 80 px.
Only the glyphs UIManager.cpp actually writes into labels using those fonts are
included, to keep flash use small. If you put new text into such a label, add
its characters below and rerun. A missing glyph renders as nothing.

Uses the same source font and options as LVGL's built-in Montserrat fonts.
Requires Node.js (npx) and a prior `pio run -e matouch21` (for the LVGL font
sources in .pio/libdeps).

    python tools/gen_matouch_fonts.py            # generate src/fonts/*.c
    python tools/gen_matouch_fonts.py --dry-run  # print the commands only
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, ".pio", "libdeps", "matouch21", "lvgl", "scripts",
                   "built_in_font", "Montserrat-Medium.ttf")
OUT_DIR = os.path.join(ROOT, "src", "fonts")
LV_FONT_CONV = "lv_font_conv@1.5.2"

FONTS = [
    # UI_FONT_40 (Dial 40 px): power_label, battery_soc_label ("%d", "--"),
    # regen/throtmax/brakeregen_value_label ("%d%%"), lock_digit_label ("%d"),
    # gear_current_label ("LOW", "HIGH", "AUTO", "HI/LO")
    ("ui_font_montserrat_80", 80, " 0123456789-%/AGHILOTUW"),
    # UI_FONT_32 (Dial 32 px): motor_current_label ("MG1+MG2", "MG1 only",
    # "MG2 only", "Blended"), lock_pin_display ("_ _ _ _" / '*' per digit)
    ("ui_font_montserrat_64", 64, " *+12BGMdelnoy_"),
]


def main():
    dry = "--dry-run" in sys.argv
    npx = shutil.which("npx")
    if not dry and not npx:
        sys.exit("npx not found - install Node.js LTS: winget install OpenJS.NodeJS.LTS")
    if not os.path.exists(TTF):
        sys.exit("Font source missing - run `pio run -e matouch21` first:\n  " + TTF)
    os.makedirs(OUT_DIR, exist_ok=True)

    for name, size, glyphs in FONTS:
        symbols = "".join(sorted(set(glyphs)))
        out = os.path.join(OUT_DIR, name + ".c")
        # Repo-relative paths: lv_font_conv records its command line in the
        # generated file, so absolute paths would leak into committed output
        rel = lambda p: os.path.relpath(p, ROOT).replace(os.sep, "/")
        cmd = [npx or "npx", "--yes", LV_FONT_CONV,
               "--no-compress", "--no-prefilter", "--bpp", "4", "--size", str(size),
               "--font", rel(TTF), "--symbols", symbols,
               "--format", "lvgl", "--force-fast-kern-format", "-o", rel(out)]
        print(" ".join('"%s"' % c if " " in c else c for c in cmd))
        if dry:
            continue
        subprocess.run(cmd, check=True, cwd=ROOT)

        # Compile for the MaTouch only; the Dial keeps LVGL's built-in fonts
        with open(out, encoding="utf-8") as f:
            body = f.read()
        body = ("/* Generated by tools/gen_matouch_fonts.py - do not edit */\n"
                "#if defined(BOARD_MATOUCH21)\n\n" + body.rstrip() +
                "\n\n#endif /* BOARD_MATOUCH21 */\n")
        with open(out, "w", encoding="utf-8", newline="\r\n") as f:
            f.write(body)
        print("  wrote %s (%d glyphs)" % (os.path.relpath(out, ROOT), len(symbols)))


if __name__ == "__main__":
    main()
